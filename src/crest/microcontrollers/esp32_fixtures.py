"""Prepared-tensor fixture staging for the ESP32 classifier backend."""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

import numpy as np



def stage_fixture_header(
    *,
    fixture_npz_path: Path,
    fixture_manifest_path: Path,
    tflite_model_path: Path,
    output_path: Path,
) -> dict[str, object]:
    """Validate prepared float tensors, quantize them, and emit a C header."""

    manifest_bytes = fixture_manifest_path.read_bytes()
    manifest = json.loads(manifest_bytes.decode("utf-8"))
    fixture_bytes = fixture_npz_path.read_bytes()
    fixture_sha256 = hashlib.sha256(fixture_bytes).hexdigest()
    expected_sha256 = manifest.get("npz_sha256")
    if expected_sha256 != fixture_sha256:
        raise ValueError("ESP32 fixture manifest npz_sha256 does not match the fixture file.")
    with np.load(fixture_npz_path, allow_pickle=False) as archive:
        if set(archive.files) != {"inputs", "ids"}:
            raise ValueError("ESP32 fixture NPZ must contain exactly inputs and ids.")
        inputs = np.asarray(archive["inputs"])
        ids = np.asarray(archive["ids"])
    if inputs.dtype != np.float32 or inputs.ndim != 3:
        raise ValueError("ESP32 fixture inputs must be float32 with shape (N,H,W).")
    if inputs.shape[0] <= 0 or not np.all(np.isfinite(inputs)):
        raise ValueError("ESP32 fixture inputs must contain finite values.")
    if ids.ndim != 1 or ids.shape[0] != inputs.shape[0] or ids.dtype.kind != "U":
        raise ValueError("ESP32 fixture ids must be a Unicode vector matching inputs.")
    normalized_ids = [str(value) for value in ids.tolist()]
    wire_ids = [
        "b64:" + base64.urlsafe_b64encode(value.encode("utf-8")).decode("ascii").rstrip("=")
        for value in normalized_ids
    ]
    if len(set(normalized_ids)) != len(normalized_ids):
        raise ValueError("ESP32 fixture ids must be unique.")
    manifest_shape = manifest.get("inputs_shape")
    if manifest_shape != list(inputs.shape) or manifest.get("inputs_dtype") != "float32":
        raise ValueError("ESP32 fixture manifest shape/dtype does not match the NPZ.")
    if manifest.get("ids") != normalized_ids:
        raise ValueError("ESP32 fixture manifest ids/order does not match the NPZ.")

    import tensorflow as tf
    from ..hardware import _quantize_tflite_tensor

    interpreter = tf.lite.Interpreter(model_path=str(tflite_model_path))
    interpreter.allocate_tensors()
    details = interpreter.get_input_details()
    if len(details) != 1:
        raise ValueError("ESP32 backend requires one TFLite input tensor.")
    detail = details[0]
    expected_shape = tuple(int(value) for value in detail["shape"])
    if len(expected_shape) != 3 or expected_shape[0] != 1:
        raise ValueError("ESP32 backend requires model input shape [1,H,W].")
    if tuple(inputs.shape[1:]) != expected_shape[1:]:
        raise ValueError(
            f"ESP32 fixture shape {tuple(inputs.shape[1:])} does not match model input {expected_shape[1:]}."
        )
    output_details = interpreter.get_output_details()
    if len(output_details) != 1 or output_details[0].get("dtype") != np.int8:
        raise ValueError("ESP32 backend requires one int8 output tensor.")
    output_shape = tuple(int(value) for value in output_details[0]["shape"])
    if not output_shape or output_shape[0] != 1:
        raise ValueError("ESP32 backend requires output batch dimension 1.")
    output_elements = int(np.prod(output_shape, dtype=np.int64))
    if output_elements <= 0:
        raise ValueError("ESP32 output tensor must contain at least one element.")
    scale, zero_point = detail["quantization"]
    if detail.get("dtype") != np.int8 or not np.isfinite(scale) or float(scale) <= 0:
        raise ValueError("ESP32 backend requires an int8 input tensor with positive finite scale.")
    quantized = np.asarray(_quantize_tflite_tensor(inputs, detail))
    if quantized.dtype != np.int8:
        raise ValueError("CREST quantization did not produce int8 fixture tensors.")
    flattened = quantized.reshape(quantized.shape[0], -1)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by CREST. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        f"static constexpr unsigned kCrestFixtureCount = {flattened.shape[0]};",
        f"static constexpr unsigned kCrestFixtureBytes = {flattened.shape[1]};",
        "static const int8_t kCrestFixtureInputs[kCrestFixtureCount][kCrestFixtureBytes] = {",
    ]
    for row in flattened:
        lines.append("  {" + ",".join(str(int(value)) for value in row) + "},")
    lines.extend(["};", "static const char *const kCrestFixtureIds[kCrestFixtureCount] = {"])
    lines.extend("  " + json.dumps(value) + "," for value in wire_ids)
    lines.extend(["};", ""])
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return {
        "fixture_sha256": fixture_sha256,
        "fixture_manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
        "fixture_manifest": manifest,
        "fixture_count": int(flattened.shape[0]),
        "fixture_bytes_per_input": int(flattened.shape[1]),
        "fixture_ids": normalized_ids,
        "fixture_wire_ids": wire_ids,
        "input_scale": float(detail["quantization"][0]),
        "input_zero_point": int(detail["quantization"][1]),
        "output_elements": output_elements,
    }
